export const tongueById = (id: string | null | undefined) => TONGUES.find((t) => t.id === id);

/** The languages a text could be by its letters alone. */
export function tonguesFor(text: string): Tongue[] {
  const letters = graphemes(text).filter((g) => /\p{L}/u.test(g));
  return TONGUES.filter((t) => letters.every((g) => g in t.alphabet));
}

/**
 * The one language a text can only be, or null when its letters fit several. Montenegrin's
 * alphabet holds all of Serbian's, so a text that fits both, with neither С́ nor З́, is Serbian.
 */
export function tongueOf(text: string): Tongue | null {
  const fits = tonguesFor(text);
  if (fits.length === 1) return fits[0]!;
  const ids = fits.map((t) => t.id).sort();
  if (ids.length === 2 && ids[0] === 'montenegrin' && ids[1] === 'serbian')
    return tongueById('serbian')!;
  return null;
}

export interface Spot {
  c: string;
  tongue: Tongue;
}

/** Every word, phrase and place whose letters say which language it is, by language. */
export const SPOTS: Record<TongueId, Spot[]> = Object.fromEntries(
  TONGUES.map((t) => [
    t.id,
    [...t.words, ...t.phrases, ...t.cities]
      .filter((r) => tongueOf(r.c)?.id === t.id)
      .map((r) => ({ c: r.c, tongue: t })),
  ]),
) as Record<TongueId, Spot[]>;
