/** Montenegrin is Serbian's alphabet plus two soft letters, С́ and З́. */
const MONTENEGRIN: Record<string, string> = { ...SERBIAN, с́: 'ś', з́: 'ź' };

/** A text as letters: a base letter with any accent written on it (С́ is one letter). */
export const graphemes = (s: string): string[] =>
  s.normalize('NFC').toLowerCase().match(/.́?/gu) ?? [];

/** Writes a Cyrillic text in Latin letters, the way the language spells it. */
export function latinOf(alphabet: Record<string, string>, text: string): string {
  let out = '';
  for (const g of text.normalize('NFC').match(/.́?/gu) ?? []) {
    const low = g.toLowerCase();
    const l = alphabet[low];
    if (l === undefined) out += g;
    else if (g !== low && l) out += l[0]!.toUpperCase() + l.slice(1);
    else out += l;
  }
  return out;
}

const reading = (alphabet: Record<string, string>) => (c: string) => ({
  c,
  l: latinOf(alphabet, c),
});

