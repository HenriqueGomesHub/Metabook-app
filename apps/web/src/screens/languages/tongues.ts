/**
 * The languages written in Cyrillic, each with its own alphabet and its own Latin spelling:
 * Г is g in Russian but h in Ukrainian, Х is kh in Russian but h in Serbian. Endless practice
 * runs one language at a time, and "Spot the language" asks which one a word is.
 */
