function koJamo(s: string): string {
  let out = '';
  for (const ch of s) {
    const code = ch.codePointAt(0) ?? 0;
    if (code >= 0xac00 && code <= 0xd7a3) {
      const S = code - 0xac00;
      out += (KO_L[Math.floor(S / 588)] ?? '') + (KO_V[Math.floor((S % 588) / 28)] ?? '');
      const t = S % 28;
      if (t) out += KO_T[t] ?? '';
    } else out += ch;
  }
  return out.toLowerCase();
}

