/* ============================================================
   Alphabet courses: learn to read a script by turning it into
   the Latin alphabet. Copied from the Alphabets app (alphabets.jsx),
   the latest version; only types added.
   ============================================================ */

/** A letter as written in the course data (Greek has upper `u` and lower `lo` forms). */
export interface RawLetter {
  c?: string;
  u?: string;
  lo?: string;
  /** how it is written in Latin ("—" for a silent sign) */
  l: string;
  /** the key it is matched by inside words, when not its own form (Thai vowels on ◌) */
  k?: string;
  name?: string;
  tip: string;
}

export interface Level {
  id: number;
  name: string;
  desc: string;
  letters: RawLetter[];
  /** an extra lesson that builds on another extra (Montenegrin on Serbian) */
  base?: number[];
}

/** A word, place or phrase: `c` in the script, `l` in Latin letters. */
export interface Reading {
  c: string;
  l: string;
}

/** A letter as the engine uses it. */
export interface Letter {
  glyph: string;
  tag: string;
  key: string;
  l: string;
  sub: string | null | undefined;
  tip: string;
}

export interface Course {
  id: string;
  name: string;
  accent: string;
  langs: string;
  blurb: string;
  sample: string[];
  l2cQ: string;
  levels: Level[];
  /** lessons outside the main course: one per language's own letters */
  extras?: Level[];
  words: Reading[];
  cities: Reading[];
  phrases: Reading[];
  fold(s: string): string;
  toLetter(r: RawLetter): Letter;
  /** courses that share a script are picked from one group (Bengali or Assamese) */
  group?: string;
  groupName?: string;
  groupSample?: string[];
  groupAccent?: string;
  groupHint?: string;
  groupBlurb?: string;
  variantLabel?: string;
  variantDesc?: string;
}

